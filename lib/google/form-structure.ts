import type { forms_v1 } from "googleapis";
import type { Question } from "@/types/question";

// Ungraded student identity questions, always the first items of a TestGenie form.
// The titles are the contract with scripts/google-forms-score-sync.gs.
export const IDENTITY_FIELD_TITLES = ["Full Name", "Roll No", "Class", "Division"] as const;
export const IDENTITY_ITEM_COUNT = IDENTITY_FIELD_TITLES.length;

export function buildFormRequests(subject: string, questions: Question[]): forms_v1.Schema$Request[] {
  return [
    // Turning the form into a quiz is what makes Google Forms auto-grade
    // responses against the correct answers set below.
    {
      updateSettings: {
        settings: { quizSettings: { isQuiz: true } },
        updateMask: "quizSettings.isQuiz",
      },
    },
    {
      updateFormInfo: {
        info: { description: `${subject} -- generated by TestGenie` },
        updateMask: "description",
      },
    },
    ...buildIdentityRequests(),
    ...questions.map((q, index) => buildQuestionRequest(q, index + IDENTITY_ITEM_COUNT)),
  ];
}

export function buildIdentityRequests(): forms_v1.Schema$Request[] {
  return IDENTITY_FIELD_TITLES.map((title, index) => buildIdentityRequest(title, index));
}

const isIdentityTextItem = (item: forms_v1.Schema$Item | undefined, title: string) => {
  const question = item?.questionItem?.question;
  return item?.title === title
    && question?.required === true
    && Boolean(question.textQuestion)
    && !question.textQuestion?.paragraph
    && !question.grading;
};

/** present: all four at positions 0-3; absent: no identity-titled text item anywhere; partial: anything else. */
export function identityFieldState(form: forms_v1.Schema$Form): "present" | "absent" | "partial" {
  const items = form.items ?? [];
  if (IDENTITY_FIELD_TITLES.every((title, index) => isIdentityTextItem(items[index], title))) return "present";
  const anyIdentity = items.some((item) =>
    Boolean(item.questionItem?.question?.textQuestion) &&
    (IDENTITY_FIELD_TITLES as readonly string[]).includes(item.title ?? "")
  );
  return anyIdentity ? "partial" : "absent";
}

function buildIdentityRequest(title: string, index: number): forms_v1.Schema$Request {
  return {
    createItem: {
      item: {
        title,
        // No grading block: identity answers carry no points and no answer key.
        questionItem: { question: { required: true, textQuestion: { paragraph: false } } },
      },
      location: { index },
    },
  };
}

function buildQuestionRequest(q: Question, index: number): forms_v1.Schema$Request {
  return {
    createItem: {
      item: {
        title: q.question,
        questionItem: {
          question: {
            required: true,
            choiceQuestion: {
              type: "RADIO",
              options: q.options.map((text) => ({ value: text })),
            },
            grading: {
              pointValue: 1,
              correctAnswers: {
                answers: [{ value: q.options[q.correctAnswerIndex] }],
              },
            },
          },
        },
      },
      location: { index },
    },
  };
}

export function formMatchesQuestions(form: forms_v1.Schema$Form, questions: Question[]): boolean {
  const items = form.items ?? [];
  if (form.settings?.quizSettings?.isQuiz !== true) return false;
  if (items.length !== IDENTITY_ITEM_COUNT + questions.length) return false;

  if (identityFieldState(form) !== "present") return false;

  return questions.every((expected, offset) => {
    const item = items[offset + IDENTITY_ITEM_COUNT];
    const actualQuestion = item.questionItem?.question;
    const actualOptions = actualQuestion?.choiceQuestion?.options?.map((option) => option.value ?? "") ?? [];
    const correctAnswers = actualQuestion?.grading?.correctAnswers?.answers?.map((answer) => answer.value ?? "") ?? [];
    return item.title === expected.question
      && actualQuestion?.choiceQuestion?.type === "RADIO"
      && actualQuestion.required === true
      && actualOptions.length === expected.options.length
      && actualOptions.every((option, optionIndex) => option === expected.options[optionIndex])
      && actualQuestion.grading?.pointValue === 1
      && correctAnswers.length === 1
      && correctAnswers[0] === expected.options[expected.correctAnswerIndex];
  });
}
