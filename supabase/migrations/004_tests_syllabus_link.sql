-- TestGenie -- link tests back to the syllabus + scope they were generated
-- from. Required so that POST /api/questions/[id]/regenerate (Phase 17) can
-- re-run RAG retrieval with the *same* syllabus/unit/topic/difficulty scope
-- the original test used, instead of guessing.
--
-- Purely additive. tests.syllabus_text (raw denormalized text) is left in
-- place unchanged for backward compatibility with existing reads/writes.

alter table public.tests
  add column if not exists syllabus_id uuid references public.syllabi(id) on delete set null,
  add column if not exists generation_config jsonb not null default '{}'::jsonb;

comment on column public.tests.syllabus_id is
  'The syllabi row this test was generated from, if generation went through the RAG pipeline. Null for legacy tests generated by pasting text directly with no stored syllabus (or for tests predating this migration).';
comment on column public.tests.generation_config is
  'Snapshot of the GenerationConfig used to create this test (unit/topic/subtopic/includedTopics/excludedTopics/additionalInstructions/questionType), so individual-question regeneration can reuse the same scope. See types/generation.ts.';

create index if not exists tests_syllabus_id_idx on public.tests(syllabus_id);
